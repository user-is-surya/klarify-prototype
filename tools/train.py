"""Trains the tiny decision tree on synthetic data and exports it as firmware/include/model.h."""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
from sklearn.tree import DecisionTreeClassifier

from dataset import make_dataset
from features import FEATURE_NAMES
from sounds import SOUNDS


@dataclass
class TrainResult:
    tree: DecisionTreeClassifier
    metrics: dict


def _emit(tree: DecisionTreeClassifier) -> str:
    t = tree.tree_
    classes = tree.classes_

    def node(i: int, ind: int) -> str:
        pad = "  " * ind
        if t.children_left[i] == -1:
            return f"{pad}return {int(classes[int(np.argmax(t.value[i][0]))])};\n"
        name = FEATURE_NAMES[t.feature[i]]
        s = f"{pad}if (f[{t.feature[i]}] <= {float(t.threshold[i])!r}) {{  // {name}\n"
        s += node(t.children_left[i], ind + 1)
        s += f"{pad}}} else {{\n"
        s += node(t.children_right[i], ind + 1)
        s += f"{pad}}}\n"
        return s

    return node(0, 1)


def _write_header(tree: DecisionTreeClassifier, out: Path) -> None:
    body = (
        "// GENERATED by tools/train.py - do not edit.\n"
        "// Decision tree trained on SYNTHETIC sounds only.\n"
        f"// classes: {', '.join(f'{i}={n}' for i, n in enumerate(SOUNDS))}\n"
        "#pragma once\n\n"
        "static inline int model_predict(const float* f) {\n"
        f"{_emit(tree)}"
        "}\n"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, newline="\n")


def train(out_header: Path, seed: int = 0, n_per_class: int = 1500) -> TrainResult:
    X, y = make_dataset(n_per_class, seed)
    tree = DecisionTreeClassifier(max_depth=8, min_samples_leaf=3, random_state=seed).fit(X, y)

    Xt, yt = make_dataset(max(n_per_class // 3, 100), seed + 1000, snr_range=(10.0, 30.0))
    pred = tree.predict(Xt)
    n = len(SOUNDS)
    conf = np.zeros((n, n), dtype=int)
    for a, b in zip(yt, pred):
        conf[a, b] += 1
    metrics = {
        "accuracy": float(np.mean(pred == yt)),
        "recall": {SOUNDS[i]: float(conf[i, i] / max(conf[i].sum(), 1)) for i in range(n)},
        "confusion": conf.tolist(),
    }
    _write_header(tree, Path(out_header))
    return TrainResult(tree=tree, metrics=metrics)


if __name__ == "__main__":
    r = train(Path("firmware/include/model.h"))
    print("Held-out accuracy on SYNTHETIC data (SNR 10-30 dB): %.3f" % r.metrics["accuracy"])
    for k, v in r.metrics["recall"].items():
        print(f"  recall {k:15s} {v:.3f}")
    print("confusion (rows=true, cols=pred; order:", ", ".join(SOUNDS), ")")
    for row in r.metrics["confusion"]:
        print("  ", row)
