"""Embeds the portal pages into firmware/include/portal.h as PROGMEM raw strings.
  firmware/portal/index.html  -> PORTAL_HTML   (served at /)
  firmware/portal/update.html -> UPDATE_HTML   (served at /update)"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGES = {
    "PORTAL_HTML": ROOT / "firmware" / "portal" / "index.html",
    "UPDATE_HTML": ROOT / "firmware" / "portal" / "update.html",
}
DELIM = ')KL"'
HEADER = ("// GENERATED by tools/embed_portal.py from firmware/portal/*.html - do not edit.\n"
          "#pragma once\n#include <pgmspace.h>\n\n")


def _array(name: str, src: Path) -> str:
    html = Path(src).read_text(encoding="utf-8")
    if DELIM in html:
        raise ValueError(f"{src.name} contains the raw-string terminator")
    return f'static const char {name}[] PROGMEM = R"KL(' + html + ')KL";\n\n'


def embed(src: Path, out: Path, name: str = "PORTAL_HTML") -> None:
    """Embed a single page."""
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_bytes((HEADER + _array(name, src)).encode("utf-8"))


def embed_all(out: Path) -> None:
    """Embed every page into one header."""
    body = HEADER + "".join(_array(n, p) for n, p in PAGES.items())
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_bytes(body.encode("utf-8"))


if __name__ == "__main__":
    embed_all(ROOT / "firmware" / "include" / "portal.h")
    print("wrote firmware/include/portal.h", file=sys.stderr)
